// UPDATED: This function now uses standard UART timing (Idle HIGH, Start LOW)
void send_laser_byte(uint8_t data)
{
    // 1. Start Bit: The receiver triggers its edge detection on this HIGH-to-LOW drop (Falling Edge)
    HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, GPIO_PIN_RESET);
    HAL_Delay(40); // START_BIT_MS

    // 2. Send 8 data bits (MSB first, matching the receiver's decoding loop)
    for(int i = 7; i >= 0; i--)
    {
        uint8_t bit_val = (data >> i) & 0x01;
        HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, bit_val ? GPIO_PIN_SET : GPIO_PIN_RESET);
        HAL_Delay(40); // BIT_PERIOD_MS
    }

    // 3. Stop bit / Rest state (Force HIGH so the next Start Bit can fall)
    HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, GPIO_PIN_SET);
    HAL_Delay(40); // STOP_BIT_MS
}
