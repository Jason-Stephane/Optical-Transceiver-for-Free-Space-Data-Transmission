/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/
  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */
  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART2_UART_Init();
  MX_TIM3_Init();

  /* USER CODE BEGIN 2 */

  // Ensure laser is OFF on startup
  HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, GPIO_PIN_RESET);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      // Wait for exactly 128 bytes from MATLAB
      if (HAL_UART_Receive(&huart2, image_buffer, 128, HAL_MAX_DELAY) == HAL_OK)
      {
          // WAKE PREAMBLE: Hold LOW to wake the receiver up
          HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, GPIO_PIN_RESET);
          HAL_Delay(1600);

          // CRITICAL PRIMER: Pull HIGH to establish the standard Idle state
          // before the first byte, allowing the first Start Bit to drop!
          HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, GPIO_PIN_SET);
          HAL_Delay(40);

          send_laser_byte(0xFF);
          send_laser_byte(0xAA);
          send_laser_byte(32);   // Width
          send_laser_byte(32);   // Height

          uint8_t checksum = 32 ^ 32;

          // Loop 128 times for the payload size
          for(int i = 0; i < 128; i++)
          {
              send_laser_byte(image_buffer[i]);
              checksum ^= image_buffer[i];
          }

          send_laser_byte(checksum);
          send_laser_byte(0x00);

          // Force laser OFF after transmission is complete
          HAL_GPIO_WritePin(LASER_GPIO_Port, LASER_Pin, GPIO_PIN_RESET);
      }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

